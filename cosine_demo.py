import numpy as np
import pickle
from sentence_transformers import SentenceTransformer
from sklearn.metrics.pairwise import cosine_similarity

# ============================================================================
# КОСИНУСНОЕ СОБОДСТВО: ДЕМОНСТРАЦИЯ СЕМАНТИЧЕСКОГО ПОИСКА
# ============================================================================
# Этот скрипт демонстрирует базовый принцип семантического поиска через
# вычисление косинусного сходства между векторными представлениями текстов.
# ============================================================================

# Загрузка данных
# -----------------------------------------------------------------------------
# docs.pkl: Список текстовых чанков
# embeddings.npy: NumPy массив с числовыми векторными представлениями
with open("docs.pkl", "rb") as f:
    docs = pickle.load(f)

embeddings = np.load("embeddings.npy")
# -----------------------------------------------------------------------------

# Загрузка модели для кодирования запросов
# -----------------------------------------------------------------------------
model = SentenceTransformer('all-MiniLM-L6-v2')
# -----------------------------------------------------------------------------

def show_cosine_distances(query: str):
    """
    ============================================================================
    ФУНКЦИЯ: show_cosine_distances
    ============================================================================
    ОПИСАНИЕ:
        Вычисляет и выводит косинусное сходство и расстояние между запросом
        и каждым документом из коллекции.
    --------------------------------------------------------------------------
    ПАРАМЕТРЫ:
        query (str): Строковый запрос, например, «машинное обучение»
    --------------------------------------------------------------------------
    АЛГОРИТМ:
        1. Кодирует запрос в вектор с помощью предобученной модели.
        2. Вычисляет косинусное сходство между вектором запроса и каждым
           документом.
        3. Вычисляет косинусное расстояние.
    --------------------------------------------------------------------------
    МЕТРИКИ:
        • Косинусное сходство: [-1, 1], чем ближе к 1, тем более похожи тексты.
        • Косинусное расстояние: [0, 2], чем ближе к 0, тем более похожи тексты.
    ============================================================================
    """
    # Кодируем запрос в вектор
    q_emb = model.encode([query])
    
    # Вычисляем косинусное сходство между вектором запроса и всеми эмбеддингами
    # cosine_similarity возвращает матрицу
    similarities = cosine_similarity(q_emb, embeddings)[0]
    
    # Косинусное расстояние = 1 - косинусное сходство
    distances = 1 - similarities

    print(f"\nЗапрос: '{query}'\n")
    for i, (doc, sim, dist) in enumerate(zip(docs, similarities, distances)):
        print(f"Документ {i}:")
        print(f"  Текст: {doc[:100]}...")
        print(f"  Косинусное сходство: {sim:.4f}")
        print(f"  Косинусное расстояние: {dist:.4f}\n")

if __name__ == "__main__":
    # ========================================================================
    # ТОЧКА ВХОДА В СКРИПТ
    # ========================================================================
    # При запуске выполняется:
    #   1. Создаётся тестовый запрос
    #   2. Вызывается функция show_cosine_distances
    # ========================================================================
    test_query = "машинное обучение"
    show_cosine_distances(test_query)