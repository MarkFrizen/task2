# Импорт библиотеки для работы с предобученными моделями трансформеров
from sentence_transformers import SentenceTransformer
# Импорт клиента для взаимодействия с векторной базой данных Qdrant
from qdrant_client import QdrantClient

# Инициализация той же модели, что использовалась при индексации
# Модель 'all-MiniLM-L6-v2' для генерации 384-мерных векторных эмбеддингов
model = SentenceTransformer('all-MiniLM-L6-v2')
# Подключение к локальному экземпляру Qdrant на порту 6333
client = QdrantClient(host="localhost", port=6333)

# Предустановленные тестовые запросы для удобства
# Эти запросы можно использовать для быстрого теста поиска
PRESET_QUERIES = [
    "машинное обучение",
    "векторы",
    "поиск по смыслу",
    "эмбеддинги",
    "документ",
    "предложения"
]

def search(query: str, top_k: int = 5):
    """Выполняет семантический поиск по запросу.
    
    Args:
        query (str): Поисковый запрос (текстовый запрос пользователя)
        top_k (int): Количество релевантных результатов для возврата (по умолчанию 5)
    
    Returns:
        list: Список найденных точек (чанков документов) с наивысшим сходством
              к вектору запроса, отсортированных по убыванию релевантности
    """
    # Преобразование текстового запроса в векторное представление
    # model.encode() возвращает массив эмбеддингов, поэтому берём первый элемент [0]
    # .tolist() преобразует numpy-массив в Python-список для Qdrant
    vec = model.encode([query])[0].tolist()
    
    # Выполнение поиска в коллекции 'my_docs'
    # - query=vec: вектор запроса для поиска
    # - limit=top_k: максимальное количество результатов
    # - with_payload=True: включить метаданные (source, chunk_id, text) в результат
    results = client.query_points(
        collection_name="my_docs",
        query=vec,
        limit=top_k,
        with_payload=True
    )
    
    # Возвращаем только список найденных точек (без метаданных ответа Qdrant)
    return results.points


if __name__ == "__main__":
    """Основной цикл взаимодействия с пользователем для поиска."""
    
    print("\n=== Семантический поиск ===")
    print("Выберите запрос (введите номер) или 0 для ручного ввода:\n")
    
    # Вывод предустановленных запросов с номерами
    for i, q in enumerate(PRESET_QUERIES, start=1):
        print(f"  {i}. {q}")
    print("  0. Ввести свой запрос")
    
    # Получение выбора пользователя
    choice = input("\nВаш выбор: ").strip()
    
    # Обработка выбора пользователя
    if choice == "0":
        # Ручной ввод пользовательского запроса
        query = input("Введите запрос: ").strip()
    else:
        try:
            # Попытка преобразовать ввод в целое число
            idx = int(choice) - 1
            # Проверка корректности индекса
            if 0 <= idx < len(PRESET_QUERIES):
                query = PRESET_QUERIES[idx]
            else:
                # Неверный номер, используем первый запрос по умолчанию
                print("Неверный номер, использую первый запрос.")
                query = PRESET_QUERIES[0]
        except ValueError:
            # Неверный формат ввода, используем первый запрос по умолчанию
            print("Неверный ввод, использую первый запрос.")
            query = PRESET_QUERIES[0]
    
    # Отображение выполняемого запроса
    print(f"\nЗапрос: {query}\n")
    
    # Выполнение поиска
    results = search(query)
    
    # Обработка и вывод результатов
    if not results:
        print("Ничего не найдено.")
    else:
        print("Результаты:")
        # Вывод найденных чанков с метаданными и оценкой релевантности
        for i, hit in enumerate(results, start=1):
            # Нумерация результатов
            print(f"{i}. {hit.payload['source']} (чанк {hit.payload['chunk_id']})")
            # Отображение начала текста чанка (первые 150 символов)
            print(f"   {hit.payload['text'][:150]}...")
            # Оценка релевантности (косинусное сходство)
            print(f"   score: {hit.score:.4f}\n")