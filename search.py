from sentence_transformers import SentenceTransformer
from qdrant_client import QdrantClient

# ============================================================================
# SEARCH.PY: СЕМАНТИЧЕСКИЙ ПОИСК ЧЕРЕЗ QDRANT
# ============================================================================
# Этот скрипт обеспечивает интерактивный поиск по коллекции документов,
# ранее созданной в index.py. Он использует Qdrant Client для выполнения
# запросов к векторной базе данных и получения релевантных результатов.
# ============================================================================

# Инициализация клиентов
# -----------------------------------------------------------------------------
# Модель для кодирования запросов
model = SentenceTransformer('all-MiniLM-L6-v2')

# Клиент для подключения к Qdrant
client = QdrantClient(host="localhost", port=6333)
# -----------------------------------------------------------------------------

# Предустановленные запросы для удобства
# -----------------------------------------------------------------------------
# Список тестовых запросов, которые можно выбрать при запуске скрипта
PRESET_QUERIES = [
    "машинное обучение",
    "векторы",
    "поиск по смыслу",
    "эмбеддинги",
    "документ",
    "предложения"
]
# -----------------------------------------------------------------------------

def search(query: str, top_k: int = 5):
    """
    ============================================================================
    ФУНКЦИЯ: search
    ============================================================================
    ОПИСАНИЕ:
        Выполняет семантический поиск по коллекции my_docs в Qdrant.
        Преобразует текстовый запрос в вектор и находит ближайшие документы.
    --------------------------------------------------------------------------
    ПАРАМЕТРЫ:
        query (str): Текстовый запрос пользователя
        top_k (int): Количество результатов для возврата
    --------------------------------------------------------------------------
    ВОЗВРАЩАЕТ:
        List[PointStruct]: Список найденных точек с метаданными и оценками.
                          Каждая точка содержит:
                            • id: Уникальный идентификатор
                            • vector: Векторное представление
                            • payload: Метаданные (source, chunk_id, text)
                            • score: Релевантность
    --------------------------------------------------------------------------
    АЛГОРИТМ:
        1. Кодирует запрос в вектор с помощью SentenceTransformer.
        2. Отправляет вектор в Qdrant через query_points.
        3. Qdrant находит top_k ближайших соседей по косинусному сходству.
        4. Возвращает точки с метаданными.
    ============================================================================
    """
    # Преобразуем запрос в вектор и преобразуем в list для API
    vec = model.encode([query])[0].tolist()
    
    # Выполняем запрос к Qdrant
    results = client.query_points(
        collection_name="my_docs",
        query=vec,
        limit=top_k,
        with_payload=True
    )
    
    # Возвращаем список найденных точек
    return results.points

if __name__ == "__main__":
    # ========================================================================
    # ТОЧКА ВХОДА: ИНТЕРКАТИВНЫЙ ПОИСК
    # ========================================================================
    # При запуске скрипта:
    #   1. Выводит меню с предустановленными запросами
    #   2. Позволяет выбрать запрос из списка или ввести свой
    #   3. Выполняет поиск и выводит результаты в консоль
    # ========================================================================
    print("\n=== Семантический поиск (Qdrant) ===")
    print("Выберите запрос (введите номер) или 0 для ручного ввода:\n")
    
    # Вывод меню с предустановленными запросами
    for i, q in enumerate(PRESET_QUERIES, start=1):
        print(f"  {i}. {q}")
    print("  0. Ввести свой запрос")
    
    # Чтение выбора пользователя
    choice = input("\nВаш выбор: ").strip()
    
    # Обработка выбора
    if choice == "0":
        # Ручной ввод запроса
        query = input("Введите запрос: ").strip()
    else:
        # Выбор из списка
        try:
            idx = int(choice) - 1
            if 0 <= idx < len(PRESET_QUERIES):
                query = PRESET_QUERIES[idx]
            else:
                print("Неверный номер, использую первый запрос.")
                query = PRESET_QUERIES[0]
        except ValueError:
            print("Неверный ввод, использую первый запрос.")
            query = PRESET_QUERIES[0]
    
    # Выполнение поиска и вывод результатов
    print(f"\nЗапрос: {query}\n")
    results = search(query)
    
    if not results:
        print("Ничего не найдено.")
    else:
        print("Результаты:")
        for i, hit in enumerate(results, start=1):
            print(f"{i}. {hit.payload['source']} чанк {hit.payload['chunk_id']}")
            print(f"   {hit.payload['text'][:150]}...")
            print(f"   score: {hit.score:.4f}\n")