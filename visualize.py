import numpy as np
import matplotlib.pyplot as plt
from sklearn.decomposition import PCA
from sklearn.manifold import TSNE
import pickle

# ============================================================================
# VISUALIZE.PY: ВИЗУАЛИЗАЦИЯ ВЕКТОРНЫХ ПРЕДСТАВЛЕНИЙ (EMBEDDINGS)
# ============================================================================
# Этот скрипт строит 2D и 3D проекции высокоразмерных векторов для
# визуальной оценки качества эмбеддингов. Используются методы:
#   • PCA (Principal Component Analysis) — линейное преобразование
#   • t-SNE (t-Distributed Stochastic Neighbor Embedding) — нелинейное
# ============================================================================

# Загрузка данных
# -----------------------------------------------------------------------------
# embeddings.npy: Массив векторных представлений (384-мерные векторы)
# docs.pkl: Список текстовых чанков (для подписей на графике)
embeddings = np.load("embeddings.npy")
with open("docs.pkl", "rb") as f:
    docs = pickle.load(f)
# -----------------------------------------------------------------------------

# ----- 2D ВИЗУАЛИЗАЦИЯ ЧЕРЕЗ PCA -----
# ============================================================================
# PCA (Principal Component Analysis) — метод линейного снижения размерности.
# Находит направления максимальной дисперсии в данных и проецирует их на
# подпространство меньшей размерности (в данном случае — 2D).
# ============================================================================
pca = PCA(n_components=2)
emb_2d = pca.fit_transform(embeddings)

plt.figure(figsize=(10, 8))
plt.scatter(emb_2d[:, 0], emb_2d[:, 1], alpha=0.7)

# Подписываем первые 10 документов (или все, если их меньше 10)
for i, txt in enumerate(docs):
    if i < 10:
        plt.annotate(f"Doc{i}", (emb_2d[i, 0], emb_2d[i, 1]), fontsize=8)

plt.title("PCA 2D проекция эмбеддингов")
plt.xlabel("PC1 (первый главный компонент)")
plt.ylabel("PC2 (второй главный компонент)")
plt.grid(True)
plt.show()
# ============================================================================

# ----- 3D ВИЗУАЛИЗАЦИЯ -----
# ============================================================================
# Для 3D проекции используем t-SNE, если документов > 2, иначе PCA.
# --------------------------------------------------------------------------
# Почему t-SNE для 3D?
#   • PCA — линейный метод, может не сохранить сложные структуры.
#   • t-SNE — нелинейный метод, лучше сохраняет локальные кластеры,
#     но работает медленнее и может давать разные результаты при каждом запуске.
# --------------------------------------------------------------------------
# Важно: perplexity (параметр t-SNE) должна быть < числа образцов.
# --------------------------------------------------------------------------
if len(embeddings) > 2:
    # perplexity должно быть меньше числа образцов (обычно 5-30)
    perplexity = min(30, len(embeddings) - 1)
    tsne = TSNE(n_components=3, perplexity=perplexity, random_state=42)
    emb_3d = tsne.fit_transform(embeddings)
    method = "t-SNE"
else:
    pca3 = PCA(n_components=3)
    emb_3d = pca3.fit_transform(embeddings)
    method = "PCA"

fig = plt.figure(figsize=(12, 10))
ax = fig.add_subplot(111, projection='3d')
ax.scatter(emb_3d[:, 0], emb_3d[:, 1], emb_3d[:, 2], alpha=0.7)

# Подписываем первые 10 документов
for i, txt in enumerate(docs):
    if i < 10:
        ax.text(emb_3d[i, 0], emb_3d[i, 1], emb_3d[i, 2], f"Doc{i}", fontsize=8)

ax.set_title(f"{method} 3D проекция эмбеддингов")
ax.set_xlabel("X")
ax.set_ylabel("Y")
ax.set_zlabel("Z")
plt.show()