import faiss
import numpy as np
import pickle
from sentence_transformers import SentenceTransformer

# ============================================================================
# FAISS: БЫСТРЫЙ ПОИСК БЛИЖАЙШИХ СОСЕДЕЙ
# ============================================================================
# FAISS — библиотека от Meta для эффективного
# поиска по векторам. Использует индексацию и приближённые алгоритмы для
# ускорения поиска в больших коллекциях.
# ============================================================================

# Загрузка сохранённых данных
# -----------------------------------------------------------------------------
# docs.pkl: Список текстовых чанков, сгенерированных в index.py
# metadatas.pkl: Список словарей с метаданными для каждого чанка
with open("docs.pkl", "rb") as f:
    docs = pickle.load(f)

with open("metadatas.pkl", "rb") as f:
    metadatas = pickle.load(f)

embeddings = np.load("embeddings.npy")
# -----------------------------------------------------------------------------

# Нормализация векторов для косинусного сходства
# -----------------------------------------------------------------------------
# Для вычисления косинусного сходства через скалярное произведение
# необходимо, чтобы векторы были нормализованы.
# После нормализации:
#   cosine_similarity = dot
# -----------------------------------------------------------------------------
embeddings_norm = embeddings / np.linalg.norm(embeddings, axis=1, keepdims=True)
# -----------------------------------------------------------------------------

# Создание FAISS индекса
# -----------------------------------------------------------------------------
# IndexFlatIP — полнотекстовый поиск по скалярному произведению.
# Работает только с нормализованными векторами и эффективно вычисляет
# косинусное сходство. Это простой, но точный алгоритм.
#
# dim = 384 — размерность векторов, соответствует выходу модели SentenceTransformer.
# -----------------------------------------------------------------------------
dim = embeddings.shape[1]
index = faiss.IndexFlatIP(dim)
index.add(embeddings_norm)
# -----------------------------------------------------------------------------

# Загрузка модели для кодирования запросов
# -----------------------------------------------------------------------------
# Используется та же модель, что и в index.py и cosine_demo.py
model = SentenceTransformer('all-MiniLM-L6-v2')
# -----------------------------------------------------------------------------

def search_faiss(query: str, top_k: int = 5):
    """
    ============================================================================
    ФУНКЦИЯ: search_faiss
    ============================================================================
    ОПИСАНИЕ:
        Выполняет семантический поиск по коллекции документов через FAISS.
        Возвращает топ-k наиболее релевантных результатов с метаданными.
    --------------------------------------------------------------------------
    ПАРАМЕТРЫ:
        query (str): Текстовый запрос, например, «векторы»
        top_k (int): Количество результатов для возврата
    --------------------------------------------------------------------------
    ВОЗВРАЩАЕТ:
        list[dict]: Список результатов, каждый из которых содержит:
            • text (str): Текст документа
            • metadata (dict): Метаданные (source, chunk_id)
            • score (float): Косинусное сходство
    --------------------------------------------------------------------------
    АЛГОРИТМ:
        1. Кодирует запрос в вектор с помощью модели SentenceTransformer.
        2. Нормализует вектор запроса.
        3. Ищет top_k ближайших соседей в FAISS-индексе.
        4. Формирует список результатов с метаданными.
    ============================================================================
    """
    # Кодируем запрос и нормализуем
    q_emb = model.encode([query])
    q_emb_norm = q_emb / np.linalg.norm(q_emb)
    
    # Поиск в индексе
    scores, indices = index.search(q_emb_norm, top_k)
    
    # Формируем список результатов
    results = []
    for idx, score in zip(indices[0], scores[0]):
        results.append({
            "text": docs[idx],
            "metadata": metadatas[idx],
            "score": float(score)
        })
    return results

if __name__ == "__main__":
    # ========================================================================
    # ТОЧКА ВХОДА В СКРИПТ
    # ========================================================================
    # При запуске выполняет поиск по предопределённому запросу
    # и выводит результаты в консоль.
    # ========================================================================
    test_query = "машинное обучение"
    print(f"Поиск через FAISS по запросу: '{test_query}'\n")
    results = search_faiss(test_query)
    for i, res in enumerate(results, 1):
        print(f"{i}. {res['metadata']['source']} чанк {res['metadata']['chunk_id']}")
        print(f"   {res['text'][:150]}...")
        print(f"   score косинусное сходство: {res['score']:.4f}\n")